# 正则规则按照优先级排列，优先识别更具体、较长的内容
正则规则 = [
    ("CREDIT_CODE", re.compile(r"(?<![0-9A-Z])[0-9A-HJ-NPQRTUWXY]{18}(?![0-9A-Z])", re.IGNORECASE)),
    ("ID_CARD", re.compile(r"(?<!\d)\d{17}[0-9Xx](?![0-9A-Za-z])")),
    ("PHONE", re.compile(r"(?<!\d)(?:\+?86[-\s]?)?1[3-9]\d{9}(?!\d)")),
    ("EMAIL", re.compile(r"(?<![\w.+-])[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}(?![\w.-])")),
    ("DATE", re.compile(r"(?<!\d)(?:19|20)\d{2}\s*[年./-]\s*(?:0?[1-9]|1[0-2])\s*(?:月|[./-])\s*(?:0?[1-9]|[12]\d|3[01])\s*日?(?!\d)")),
    ("AMOUNT", re.compile(r"(?<![\d.])(?:人民币\s*)?[¥￥]?\s*\d{1,3}(?:,\d{3})*(?:\.\d+)?\s*(?:万|亿)?\s*元(?:人民币)?|(?<![\d.])(?:人民币\s*)?[¥￥]?\s*\d+(?:\.\d+)?\s*(?:万|亿)元?(?![\d.])")),
    ("PERCENT", re.compile(r"(?<![\d.])\d+(?:\.\d+)?\s*[%％](?!\d)")),
]


# Company 和 Person 遇到以下字段、其他当事方标签或空行时立即停止
终止字段规则 = (
    r"(?:统一社会信用代码|身份证号|法定代表人|联系人|电话|邮寄地址|"
    r"执行事务合伙人委派代表|执行事务合伙人|电子邮箱|传真|开户银行|银行账号)"
)
当事方标签规则 = r"(?:甲方|乙方|丙方|丁方|戊方)"
字段边界规则 = rf"(?:{当事方标签规则}|{终止字段规则})[ \t]*[：:]"
内容终止规则 = (
    rf"(?=(?:[ \t]*\r?\n)?[ \t]*{字段边界规则}|"
    rf"[ \t]*\r?\n[ \t]*\r?\n|[；;，,]|[ \t]*$)"
)


# 标签后允许一个普通换行，但不跨越空行，标签本身保留不变
主体标签规则 = re.compile(
    rf"{当事方标签规则}[ \t]*[：:][ \t]*(?:\r?\n[ \t]*)?"
    rf"([^\n\r；;，,]+?){内容终止规则}"
)
人员标签规则 = re.compile(
    r"(?:法定代表人|联系人|执行事务合伙人委派代表)[ \t]*[：:][ \t]*(?:\r?\n[ \t]*)?"
    rf"([^\n\r；;，,]+?){内容终止规则}"
)
电话标签规则 = re.compile(
    r"电话\s*[：:]\s*([^\n\r；;，,]+?)"
    r"(?=\s*(?:甲方|乙方|丙方|丁方|戊方|法定代表人|联系人|执行事务合伙人委派代表|电话|邮寄地址)\s*[：:]|$)"
)
地址标签规则 = re.compile(
    r"邮寄地址\s*[：:]\s*([^\n\r；;]+?)"
    r"(?=\s*(?:甲方|乙方|丙方|丁方|戊方|法定代表人|联系人|执行事务合伙人委派代表|电话|邮寄地址)\s*[：:]|$)"
)


# 签字页规则：签字人优先识别为 PERSON；盖章主体需要具有机构特征
签字主体规则 = re.compile(
    r"([^\n\r：:；;，,（）()]{1,50}?)\s*[（(]\s*签字\s*[）)]"
)
盖章主体规则 = re.compile(
    r"([^\n\r：:；;，,]{1,100}?)\s*[（(]\s*盖章\s*[）)]"
)
# 主体只有包含明确公司关键词时才识别为 COMPANY，否则默认识别为 PERSON
公司主体特征规则 = re.compile(
    r"(?:股份有限公司|有限责任公司|有限公司|有限合伙|集团|企业|公司)"
)


