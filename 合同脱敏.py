def 恢复段落(段落, 映射表):
    """只遍历 Mapping，恢复一个段落中的全部占位符。"""
    恢复数量 = 0
    候选位置 = []

    # 不重新识别任何内容，只查找 Mapping 中明确存在的键
    for 占位符名称, 原文 in 映射表.items():
        占位符 = f"[[{占位符名称}]]"
        搜索起点 = 0
        while True:
            起点 = 段落.text.find(占位符, 搜索起点)
            if 起点 < 0:
                break
            终点 = 起点 + len(占位符)
            候选位置.append((起点, 终点, str(原文)))
            搜索起点 = 终点

    # 从右向左恢复全部出现位置，保留占位符所在文字片段的字体和样式
    for 起点, 终点, 原文 in sorted(候选位置, reverse=True):
        替换段落区间(段落, 起点, 终点, 原文)
        恢复数量 += 1

    return 恢复数量


def 恢复原文(合同, 映射表):
    """只根据 Mapping 恢复正文、表格、页眉和页脚中的原文。"""
    恢复数量 = 0
    for 段落 in 遍历全部段落(合同):
        恢复数量 += 恢复段落(段落, 映射表)
    return 恢复数量


