"""
本地合同脱敏工具。

使用方法：
1. 将一个 .docx 文件放入“输入文件”目录，文件名可以任意。
2. 运行：python 合同脱敏.py
3. 按提示选择“脱敏”或“恢复”。

恢复 AI 返回的 Word：
1. 将“原文件--AI审查.docx”放入“输入文件”目录。
2. 保留“输出文件”中的“原文件--映射.json”。
3. 选择“恢复”，程序会自动寻找同名 Mapping。

也可以直接运行：
python 合同脱敏.py 脱敏
python 合同脱敏.py 恢复
"""

