def 准备目录():
    """创建输入、输出目录。"""
    输入目录.mkdir(parents=True, exist_ok=True)
    输出目录.mkdir(parents=True, exist_ok=True)


def 选择文件(候选文件, 提示文字):
    """存在多个 Word 时显示中文编号，让用户选择要处理的文件。"""
    print(提示文字)
    for 编号, 文件 in enumerate(候选文件, start=1):
        print(f"{编号}. {文件.name}")

    while True:
        选择内容 = input("请输入文件编号：").strip()
        if 选择内容.isdigit():
            选择编号 = int(选择内容)
            if 1 <= 选择编号 <= len(候选文件):
                return 候选文件[选择编号 - 1]
        print("输入无效，请重新输入。")


def 查找输入合同():
    """查找原始合同，存在多个文件时让用户选择。"""
    候选文件 = sorted(
        文件 for 文件 in 输入目录.glob("*.docx")
        if not 文件.name.startswith("~$")
        and not 文件.stem.endswith(("--脱敏", "--AI审查", "--恢复"))
    )
    if not 候选文件:
        raise FileNotFoundError(f"“{输入目录}”中没有找到 .docx 文件。")
    if len(候选文件) > 1:
        return 选择文件(候选文件, "请选择需要脱敏的原始合同：")
    return 候选文件[0]


def 获取原始文件名(文件路径):
    """去掉后缀和流程标记，取得统一命名使用的原始文件名。"""
    文件名 = 文件路径.stem
    for 流程标记 in ("--AI审查", "--脱敏", "--恢复"):
        if 文件名.endswith(流程标记):
            return 文件名[:-len(流程标记)]
    return 文件名


def 生成脱敏文件路径(输入合同路径):
    """生成“原文件--脱敏.docx”路径。"""
    原始文件名 = 获取原始文件名(输入合同路径)
    return 输出目录 / f"{原始文件名}--脱敏.docx"


def 生成映射文件路径(输入合同路径):
    """生成“原文件--映射.json”路径。"""
    原始文件名 = 获取原始文件名(输入合同路径)
    return 输出目录 / f"{原始文件名}--映射.json"


def 确认不会覆盖文件(文件路径列表):
    """如果目标文件已经存在则停止，避免覆盖已有结果。"""
    已存在文件 = [文件路径.name for 文件路径 in 文件路径列表 if 文件路径.exists()]
    if 已存在文件:
        文件列表 = "、".join(已存在文件)
        raise FileExistsError(f"以下文件已经存在，为避免覆盖已停止操作：{文件列表}")


def 读取合同(文件路径):
    """读取 Word 合同。"""
    if not 文件路径.exists():
        raise FileNotFoundError(f"找不到文件：{文件路径}")
    return Document(str(文件路径))


def 遍历表格段落(表格):
    """递归遍历表格和嵌套表格中的所有段落。"""
    已处理单元格 = set()
    for 行 in 表格.rows:
        for 单元格 in 行.cells:
            单元格标识 = 单元格._tc
            if 单元格标识 in 已处理单元格:
                continue
            已处理单元格.add(单元格标识)
            for 段落 in 单元格.paragraphs:
                yield 段落
            for 嵌套表格 in 单元格.tables:
                yield from 遍历表格段落(嵌套表格)


def 遍历全部段落(合同):
    """遍历正文、表格、页眉和页脚中的段落。"""
    已处理段落 = set()

    def 输出未处理段落(段落列表):
        for 段落 in 段落列表:
            段落标识 = 段落._p
            if 段落标识 not in 已处理段落:
                已处理段落.add(段落标识)
                yield 段落

    yield from 输出未处理段落(合同.paragraphs)
    for 表格 in 合同.tables:
        yield from 输出未处理段落(遍历表格段落(表格))

    for 节 in 合同.sections:
        for 页眉页脚 in (节.header, 节.first_page_header, 节.even_page_header,
                         节.footer, 节.first_page_footer, 节.even_page_footer):
            yield from 输出未处理段落(页眉页脚.paragraphs)
            for 表格 in 页眉页脚.tables:
                yield from 输出未处理段落(遍历表格段落(表格))


def 清理规则内容(内容, 类别):
    """去掉规则识别结果两端的空白和常见附加说明。"""
    内容 = 内容.strip()
    if 类别 in ("COMPANY", "PERSON"):
        内容 = re.split(
            r"\s*[（(](?:以下|下称|简称|盖章|签字)", 内容, maxsplit=1
        )[0].strip()
    return 内容


def 判断主体类别(主体名称):
    """名称含公司关键词时返回 COMPANY，否则默认返回 PERSON。"""
    if 公司主体特征规则.search(主体名称):
        return "COMPANY"
    return "PERSON"


def 识别敏感信息(文本):
    """识别一段文本中的敏感信息，返回位置、类别和原文。"""
    候选结果 = []

    # “签字”明确代表自然人，优先级高于甲乙丙方产生的 COMPANY 结果
    for 匹配 in 签字主体规则.finditer(文本):
        原始内容 = 匹配.group(1)
        敏感内容 = 清理规则内容(原始内容, "PERSON")
        if 敏感内容:
            起点 = 匹配.start(1) + 原始内容.find(敏感内容)
            终点 = 起点 + len(敏感内容)
            候选结果.append((起点, 终点, "PERSON", 敏感内容, -2))

    # “盖章”本身不直接决定类别，只在名称具有明确公司特征时识别为 COMPANY
    for 匹配 in 盖章主体规则.finditer(文本):
        原始内容 = 匹配.group(1)
        敏感内容 = 清理规则内容(原始内容, "COMPANY")
        if 敏感内容 and 判断主体类别(敏感内容) == "COMPANY":
            起点 = 匹配.start(1) + 原始内容.find(敏感内容)
            终点 = 起点 + len(敏感内容)
            候选结果.append((起点, 终点, "COMPANY", 敏感内容, -1))

    # 甲乙丙方后的主体先判断是否具有公司特征，否则按自然人处理
    for 匹配 in 主体标签规则.finditer(文本):
        原始内容 = 匹配.group(1)
        临时内容 = 清理规则内容(原始内容, "PERSON")
        if not 临时内容:
            continue
        类别 = 判断主体类别(临时内容)
        敏感内容 = 清理规则内容(原始内容, 类别)
        起点 = 匹配.start(1) + 原始内容.find(敏感内容)
        终点 = 起点 + len(敏感内容)
        候选结果.append((起点, 终点, 类别, 敏感内容, 0))

    for 类别, 规则 in (("PERSON", 人员标签规则), ("PHONE", 电话标签规则),
                     ("ADDRESS", 地址标签规则)):
        for 匹配 in 规则.finditer(文本):
            原始内容 = 匹配.group(1)
            敏感内容 = 清理规则内容(原始内容, 类别)
            if not 敏感内容:
                continue
            起点 = 匹配.start(1) + 原始内容.find(敏感内容)
            终点 = 起点 + len(敏感内容)
            候选结果.append((起点, 终点, 类别, 敏感内容, 0))

    for 优先级, (类别, 规则) in enumerate(正则规则, start=1):
        for 匹配 in 规则.finditer(文本):
            敏感内容 = 匹配.group(0)
            候选结果.append((匹配.start(), 匹配.end(), 类别, 敏感内容, 优先级))

    # 先选择起点靠前、优先级更高、长度更长的结果，去掉相互重叠的识别项
    候选结果.sort(key=lambda 项: (项[0], 项[4], -(项[1] - 项[0])))
    最终结果 = []
    for 候选项 in 候选结果:
        起点, 终点, 类别, 敏感内容, _ = 候选项
        if 是字段名称(敏感内容):
            continue
        if any(起点 < 已有终点 and 终点 > 已有起点 for 已有起点, 已有终点, _, _ in 最终结果):
            continue
        最终结果.append((起点, 终点, 类别, 敏感内容))

    return sorted(最终结果, key=lambda 项: 项[0])


def 生成映射表(合同):
    """扫描整个合同，生成占位符到原文的映射。"""
    映射表 = {}
    原文索引 = {}
    类别计数 = {}
    全部识别结果 = []

    for 段落 in 遍历全部段落(合同):
        for _, _, 类别, 敏感内容 in 识别敏感信息(段落.text):
            if 是字段名称(敏感内容):
                continue
            全部识别结果.append((类别, 敏感内容))

    # 先确定每个主体的唯一类别；任何上下文识别为 PERSON 时，PERSON 优先
    主体最终类别 = {}
    for 类别, 敏感内容 in 全部识别结果:
        if 类别 not in ("COMPANY", "PERSON"):
            continue
        主体键 = 标准化文本(敏感内容)
        if 类别 == "PERSON" or 主体键 not in 主体最终类别:
            主体最终类别[主体键] = 类别

    已生成主体 = {}
    for 类别, 敏感内容 in 全部识别结果:
        if 类别 in ("COMPANY", "PERSON"):
            主体键 = 标准化文本(敏感内容)
            类别 = 主体最终类别[主体键]
            if 主体键 in 已生成主体:
                原文索引[(类别, 敏感内容)] = 已生成主体[主体键]
                continue

        索引键 = (类别, 敏感内容)
        if 索引键 in 原文索引:
            continue
        类别计数[类别] = 类别计数.get(类别, 0) + 1
        占位符名称 = f"{类别}_{类别计数[类别]:03d}"
        映射表[占位符名称] = 敏感内容
        原文索引[索引键] = 占位符名称
        if 类别 in ("COMPANY", "PERSON"):
            已生成主体[主体键] = 占位符名称

    return 映射表, 原文索引


def 替换段落区间(段落, 起点, 终点, 新内容):
    """替换段落指定区间，并尽量保留该位置原有的字符格式。"""
    游标 = 0
    涉及片段 = []

    for 片段编号, 片段 in enumerate(段落.runs):
        片段起点 = 游标
        片段终点 = 游标 + len(片段.text)
        if 片段终点 > 起点 and 片段起点 < 终点:
            涉及片段.append((片段编号, 片段, 片段起点, 片段终点))
        游标 = 片段终点

    if not 涉及片段:
        return

    _, 首片段, 首片段起点, _ = 涉及片段[0]
    _, 尾片段, 尾片段起点, _ = 涉及片段[-1]
    前缀 = 首片段.text[:起点 - 首片段起点]
    后缀 = 尾片段.text[终点 - 尾片段起点:]
    首片段.text = 前缀 + 新内容 + 后缀

    for _, 片段, _, _ in 涉及片段[1:]:
        片段.text = ""


def 是中文字符(字符):
    """判断一个字符是否为常用中文字符。"""
    return "\u3400" <= 字符 <= "\u9fff"


def 标准化文本并记录位置(文本):
    """标准化文本，同时记录每个标准字符在原文中的位置。"""
    标准字符 = []
    原文位置 = []
    位置 = 0

    while 位置 < len(文本):
        字符 = 文本[位置]

        # 统一英文括号和中文括号
        if 字符 == "(":
            标准字符.append("（")
            原文位置.append(位置)
            位置 += 1
            continue
        if 字符 == ")":
            标准字符.append("）")
            原文位置.append(位置)
            位置 += 1
            continue

        # 统一回车、换行、制表符和多个空格
        if 字符.isspace():
            空白起点 = 位置
            while 位置 < len(文本) and 文本[位置].isspace():
                位置 += 1
            if 标准字符 and 标准字符[-1] != " ":
                标准字符.append(" ")
                原文位置.append(空白起点)
            continue

        标准字符.append(字符)
        原文位置.append(位置)
        位置 += 1

    # 去掉首尾空格
    while 标准字符 and 标准字符[0] == " ":
        标准字符.pop(0)
        原文位置.pop(0)
    while 标准字符 and 标准字符[-1] == " ":
        标准字符.pop()
        原文位置.pop()

    # 去掉中文字符之间及中文括号、引号旁的空格
    # 可统一“（ 盖 章 ）”“（ 签 字 ）”“（ 以 下 简 称 ）”等写法
    紧邻符号 = "（）“”‘’"
    保留字符 = []
    保留位置 = []
    for 编号, 字符 in enumerate(标准字符):
        if 字符 == " " and 编号 > 0 and 编号 + 1 < len(标准字符):
            前字符 = 标准字符[编号 - 1]
            后字符 = 标准字符[编号 + 1]
            if ((是中文字符(前字符) and 是中文字符(后字符))
                    or 前字符 in 紧邻符号 or 后字符 in 紧邻符号):
                continue
        保留字符.append(字符)
        保留位置.append(原文位置[编号])

    return "".join(保留字符), 保留位置


def 标准化文本(文本):
    """返回用于全文匹配的标准化文本。"""
    标准文本, _ = 标准化文本并记录位置(str(文本))
    return 标准文本


def 是字段名称(内容):
    """判断内容是否只是字段名称，而不是字段对应的敏感值。"""
    标准内容 = 标准化文本(内容)
    标准内容 = re.sub(r"[：:；;，,]+$", "", 标准内容).strip()
    标准内容 = re.sub(r"（(?:签字|盖章)）$", "", 标准内容).strip()
    标准内容 = re.sub(r"[：:；;，,]+$", "", 标准内容).strip()
    return 标准内容 in 字段名称集合


def 替换敏感信息(合同, 映射表):
    """遍历 Mapping 的全部 value，在整个 Word 中替换所有出现位置。"""
    替换数量 = 0

    # Mapping value 先标准化，解决空格、换行、括号和签章文字格式不一致的问题
    标准原文到占位符 = {}
    for 占位符名称, 敏感内容 in 映射表.items():
        if 是字段名称(敏感内容):
            continue
        标准敏感内容 = 标准化文本(敏感内容)
        if not 标准敏感内容:
            continue
        已有占位符 = 标准原文到占位符.get(标准敏感内容)
        if 已有占位符 is None:
            标准原文到占位符[标准敏感内容] = 占位符名称
        elif 占位符名称.startswith("PERSON_") and not 已有占位符.startswith("PERSON_"):
            # 同一原文因上下文被分到不同类别时，签字页确认的 PERSON 优先
            标准原文到占位符[标准敏感内容] = 占位符名称

    # 长内容优先，避免公司全称和简称相互重叠时先替换简称
    替换项目 = sorted(标准原文到占位符.items(), key=lambda 项: len(项[0]), reverse=True)

    for 段落 in 遍历全部段落(合同):
        标准文本, 原文位置 = 标准化文本并记录位置(段落.text)
        候选位置 = []

        # 对每一个 Mapping value 查找全部出现位置，不能只替换第一次
        for 标准敏感内容, 占位符名称 in 替换项目:
            搜索起点 = 0
            while True:
                标准起点 = 标准文本.find(标准敏感内容, 搜索起点)
                if 标准起点 < 0:
                    break
                标准终点 = 标准起点 + len(标准敏感内容)
                起点 = 原文位置[标准起点]
                终点 = 原文位置[标准终点 - 1] + 1
                候选位置.append((起点, 终点, 占位符名称))
                搜索起点 = 标准终点

        # 同一位置优先使用较长的 value，并去掉相互重叠的候选项
        候选位置.sort(key=lambda 项: (项[0], -(项[1] - 项[0])))
        最终位置 = []
        for 起点, 终点, 占位符名称 in 候选位置:
            if any(起点 < 已有终点 and 终点 > 已有起点
                   for 已有起点, 已有终点, _ in 最终位置):
                continue
            最终位置.append((起点, 终点, 占位符名称))

        # 从右向左替换，防止文本长度变化影响前面记录的位置
        for 起点, 终点, 占位符名称 in reversed(最终位置):
            替换段落区间(段落, 起点, 终点, f"[[{占位符名称}]]")
            替换数量 += 1

    return 替换数量


def 保存映射表(映射表, 文件路径):
    """以便于人工阅读的 JSON 格式保存映射表。"""
    with 文件路径.open("w", encoding="utf-8") as 文件:
        json.dump(映射表, 文件, ensure_ascii=False, indent=4)


def 读取映射表(文件路径):
    """读取并检查脱敏映射表。"""
    if not 文件路径.exists():
        raise FileNotFoundError(f"找不到文件：{文件路径}")
    with 文件路径.open("r", encoding="utf-8") as 文件:
        映射表 = json.load(文件)
    if not isinstance(映射表, dict):
        raise ValueError("映射文件的内容必须是 JSON 对象。")
    return 映射表


def 查找对应映射文件(待恢复合同路径):
    """根据待恢复 Word 的原始文件名，自动查找同名 Mapping。"""
    原始文件名 = 获取原始文件名(待恢复合同路径)
    映射文件名 = f"{原始文件名}--映射.json"

    for 目录 in (输出目录, 输入目录, 工具目录):
        候选路径 = 目录 / 映射文件名
        if 候选路径.exists():
            return 候选路径

    raise FileNotFoundError("未找到对应 Mapping 文件，请确认 Mapping 是否存在。")


def 合同包含映射占位符(合同, 映射表):
    """只根据 Mapping 键检查 Word 是否包含待恢复占位符。"""
    占位符列表 = [f"[[{占位符名称}]]" for 占位符名称 in 映射表]
    for 段落 in 遍历全部段落(合同):
        if any(占位符 in 段落.text for 占位符 in 占位符列表):
            return True
    return False


def 查找待恢复合同():
    """按照统一命名规范自动查找 AI 审查文件或脱敏文件。"""
    候选路径 = []
    for 目录 in (输入目录, 输出目录, 工具目录):
        for 文件路径 in sorted(目录.glob("*.docx")):
            if 文件路径.name.startswith("~$") or 文件路径.stem.endswith("--恢复"):
                continue
            if 文件路径 not in 候选路径:
                候选路径.append(文件路径)

    # 优先恢复“原文件--AI审查.docx”，没有时允许直接恢复“原文件--脱敏.docx”
    审查文件 = [文件 for 文件 in 候选路径 if 文件.stem.endswith("--AI审查")]
    脱敏文件 = [文件 for 文件 in 候选路径 if 文件.stem.endswith("--脱敏")]
    匹配文件 = 审查文件 or 脱敏文件

    if not 匹配文件:
        raise FileNotFoundError(
            "没有找到待恢复文件，请将“原文件--AI审查.docx”放入“输入文件”目录。"
        )
    if len(匹配文件) > 1:
        return 选择文件(匹配文件, "请选择需要恢复的 AI 审查文件：")
    return 匹配文件[0]


def 生成恢复文件路径(待恢复文件路径):
    """生成“原文件--恢复.docx”路径。"""
    原始文件名 = 获取原始文件名(待恢复文件路径)
    return 输出目录 / f"{原始文件名}--恢复.docx"


def 保存文件(合同, 文件路径):
    """保存 Word 文件。"""
    文件路径.parent.mkdir(parents=True, exist_ok=True)
    合同.save(str(文件路径))


def 执行脱敏():
    """执行完整的合同脱敏流程。"""
    准备目录()
    输入合同路径 = 查找输入合同()
    脱敏合同路径 = 生成脱敏文件路径(输入合同路径)
